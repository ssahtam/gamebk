// ฟังก์ชันสุ่มดึงเหตุการณ์ตามอายุและประวัติการเล่น (Intelligent Age-Based Lifecycle Selector)
export function getRandomEventForAge(age, seenEventIds = new Set(), character = null) {
  let pool = [];

  // แบ่งสัดส่วนช่วงวัยอย่างแม่นยำ (Strict Age Tiering)
  if (age <= 2) {
    pool = EVENT_POOLS.INFANCY;
  } else if (age <= 6) {
    pool = EVENT_POOLS.CHILDHOOD;
  } else if (age <= 12) {
    pool = EVENT_POOLS.YOUTH;
  } else if (age <= 17) {
    pool = EVENT_POOLS.TEEN_ACADEMY;
  } else if (age <= 35) {
    pool = EVENT_POOLS.ADULT_EARLY;
  } else if (age <= 54) {
    pool = EVENT_POOLS.ADULT_PRIME;
  } else {
    pool = EVENT_POOLS.VETERAN_ELDER;
  }

  // คัดกรองเฉพาะเหตุการณ์ที่ยังไม่เคยเจอ และช่วงอายุ minAge <= age <= maxAge
  let candidates = pool.filter(e => !seenEventIds.has(e.id) && age >= (e.minAge ?? 0) && age <= (e.maxAge ?? 999));

  // Fallback 1: ถ้าเจอหมดแล้วในช่วงวัย ให้ดึงเหตุการณ์ในวัยเดียวกันที่เคยเจอได้
  if (candidates.length === 0) {
    candidates = pool.filter(e => age >= (e.minAge ?? 0) && age <= (e.maxAge ?? 999));
  }

  // Fallback 2: ถ้ายังไม่มี ให้ดึงจาก pool ทั้งหมดของวัยนั้น
  if (candidates.length === 0) {
    candidates = pool.filter(e => !seenEventIds.has(e.id));
  }

  // Fallback 3: ถ้าหมดจริงๆ
  if (candidates.length === 0) {
    candidates = pool;
  }

  const selectedEvent = candidates[Math.floor(Math.random() * candidates.length)];

  // คำนวณช่วงอายุถัดไปอย่างสมเหตุสมผล
  let ageIncrement = 1;
  if (age >= 55) ageIncrement = 4;
  else if (age >= 35) ageIncrement = 3;
  else if (age >= 18) ageIncrement = 2;
  else if (age >= 13) ageIncrement = 2;
  else if (age >= 3) ageIncrement = 1;
  else ageIncrement = 1;

  const nextAge = age + ageIncrement;

  return {
    ...selectedEvent,
    age: age,
    nextAge: nextAge
  };
}
