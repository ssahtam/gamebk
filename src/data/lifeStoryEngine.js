// ตรวจสอบความพร้อมทางสรีระของช้อย (Physical & Biological Feasibility Check)
export function checkChoiceAvailability(choice, character) {
  const bodyType = character?.race?.bodyType || 'humanoid';

  // 1. ตรวจสอบช้อยเฉพาะเผ่า (Exclusive)
  if (choice.exclusiveBody && choice.exclusiveBody !== bodyType) {
    if (choice.exclusiveBody === 'slime') return { locked: true, reason: 'สงวนเฉพาะสไลม์ (ร่างกายต้องเป็นเจลลี่)' };
    if (choice.exclusiveBody === 'skeleton') return { locked: true, reason: 'สงวนเฉพาะโครงกระดูก (ต้องมีร่างกายไร้เนื้อหนัง)' };
    if (choice.exclusiveBody === 'spider') return { locked: true, reason: 'สงวนเฉพาะแมงมุม (ต้องมี 8 ขาและต่อมใย)' };
    if (choice.exclusiveBody === 'sword') return { locked: true, reason: 'สงวนเฉพาะดาบมีชีวิต (ต้องเป็นศาสตราวิญญาณ)' };
    if (choice.exclusiveBody === 'truck') return { locked: true, reason: 'สงวนเฉพาะจักรกลรถบรรทุก' };
    if (choice.exclusiveBody === 'beast') return { locked: true, reason: 'สงวนเฉพาะสัตว์สี่ขา (แมว/หมา/จิ้งจอก/คาปิบารา)' };
    if (choice.exclusiveBody === 'mimic') return { locked: true, reason: 'สงวนเฉพาะกล่องมิมิกกินคน' };
    if (choice.exclusiveBody === 'object') return { locked: true, reason: 'สงวนเฉพาะวัตถุสิ่งของ (ตู้กดน้ำ/ไม้กวาด/โกเลม/กระบองเพชร)' };
  }

  // 2. ตรวจสอบข้อห้ามทางสรีระ (Forbidden)
  if (choice.forbiddenBody && choice.forbiddenBody.includes(bodyType)) {
    if (bodyType === 'slime') {
      if (choice.reqLimbs === 'hands') return { locked: true, reason: 'สไลม์ไม่มีมือจับอาวุธ (เป็นเพียงก้อนเจลลี่)' };
      if (choice.reqLimbs === 'legs') return { locked: true, reason: 'สไลม์ไม่มีขา/เท้า (ไม่สามารถเตะหรือวิ่งสองขาได้)' };
      return { locked: true, reason: 'สรีระสไลม์ไม่สามารถทำสิ่งนี้ได้' };
    }
    if (bodyType === 'skeleton') {
      if (choice.reqOrganic === 'eat') return { locked: true, reason: 'โครงกระดูกไม่มีกระเพาะอาหาร (กินไปก็ร่วงผ่านซี่โครงลงพื้น)' };
      if (choice.reqOrganic === 'tears') return { locked: true, reason: 'โครงกระดูกไม่มีต่อมน้ำตา (ร้องไห้ไม่ได้)' };
      return { locked: true, reason: 'โครงกระดูกไร้เนื้อหนังทำสิ่งนี้ไม่ได้' };
    }
    if (bodyType === 'sword') {
      if (choice.reqLimbs === 'legs' || choice.reqLimbs === 'hands') return { locked: true, reason: 'ดาบไม่มีแขนขา (ต้องรอคนมาถือหรือสะสมพลังจิตลอยตัว)' };
      if (choice.reqOrganic === 'eat') return { locked: true, reason: 'ดาบโลหะไม่กินอาหารอินทรีย์' };
      return { locked: true, reason: 'ดาบโลหะไม่สามารถขยับแบบสิ่งมีชีวิตได้' };
    }
    if (bodyType === 'spider') {
      if (choice.reqLimbs === 'hands') return { locked: true, reason: 'แมงมุมมีแต่ขาแมลง ไม่มีนิ้วมือจับด้ามดาบแบบมนุษย์' };
      return { locked: true, reason: 'สรีระแมงมุมไม่รองรับ' };
    }
    if (bodyType === 'truck') {
      if (choice.reqLimbs === 'hands' || choice.reqLimbs === 'legs') return { locked: true, reason: 'รถบรรทุก 10 ล้อไม่มีแขนขาแบบคน' };
      if (choice.reqOrganic === 'eat') return { locked: true, reason: 'รถบรรทุกไม่กินข้าว กินแต่น้ำมันดีเซลและวิญญาณ' };
      return { locked: true, reason: 'ยานพาหนะไม่สามารถทำได้' };
    }
    if (bodyType === 'object') {
      if (choice.reqLimbs === 'hands' || choice.reqLimbs === 'legs') return { locked: true, reason: 'วัตถุสิ่งของไม่มีแขนขาเดิน' };
      return { locked: true, reason: 'สิ่งของไม่มีชีวิตไม่สามารถทำได้' };
    }
  }

  return { locked: false, reason: '' };
}

