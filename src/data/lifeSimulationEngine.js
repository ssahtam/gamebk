// 4. ฟังก์ชันดึงการตัดสินใจตามอายุและสายพันธุ์แบบแม่นยำ พร้อมระบบสุ่มหลายทางเลือกไม่ซ้ำซาก
// ==========================================
export function getMajorDecisionForAge(age, character, seenDecisionIds = new Set()) {
  const taxonomy = getTaxonomyCategory(character?.race);
  const raceId = (character?.race?.id || '').toLowerCase();
  const bodyType = (character?.race?.bodyType || taxonomy || '').toLowerCase();

  let targetPool = [];

  // 1. รถบรรทุกอิเซไก & หุ่นยนต์ดูดฝุ่นข้ามมิติ
  if (raceId === 'truck_calamity' || bodyType === 'truck' || raceId.includes('truck') || raceId === 'roomba') {
    targetPool = TRUCK_MAJOR_DECISIONS;
  }
  // 2. สิ่งของมีชีวิต & ตู้กดน้ำ & ดาบ & มิมิก
  else if (taxonomy === 'object' || bodyType === 'sword' || bodyType === 'mimic' || bodyType === 'object') {
    targetPool = OBJECT_MAJOR_DECISIONS;
  }
  // 3. สัตว์ปีก สัตว์อสูร นกพิราบ มังกร คาปิบาร่า กุ้งสไนเปอร์ แมว หมา
  else if (
    taxonomy === 'beast' || 
    bodyType === 'bird' || 
    bodyType === 'beast' || 
    bodyType === 'dragon' || 
    bodyType === 'lobster' || 
    raceId.includes('pigeon') || 
    raceId.includes('capybara') || 
    raceId.includes('cat') || 
    raceId.includes('corgi') ||
    raceId.includes('chicken') ||
    raceId.includes('wolf')
  ) {
    targetPool = BEAST_MAJOR_DECISIONS;
  }
  // 4. อันเดด โครงกระดูก วิญญาณเร่ร่อน ราชันย์เถ้า
  else if (
    taxonomy === 'undead' || 
    bodyType === 'skeleton' || 
    bodyType === 'ghost' || 
    raceId.includes('skeleton') || 
    raceId.includes('ashen')
  ) {
    targetPool = UNDEAD_MAJOR_DECISIONS;
  }
  // 5. มอนสเตอร์ สไลม์ ก็อบลิน แมงมุม เห็ดพิษ
  else if (
    taxonomy === 'monster' || 
    bodyType === 'slime' || 
    bodyType === 'goblin' || 
    bodyType === 'spider' || 
    bodyType === 'mushroom'
  ) {
    targetPool = MONSTER_MAJOR_DECISIONS;
  }
  // 6. มนุษย์และสายพันธุ์ humanoid ทั่วไป
  else {
    targetPool = HUMANOID_MAJOR_DECISIONS;
  }

  // ค้นหาการตัดสินใจตามช่วงอายุ
  let matches = targetPool.filter(d => d.age === age);

  // Fallback: หาก pool เผ่าไม่มีของอายุนั้น ให้ดึงจาก humanoid
  if (matches.length === 0) {
    matches = HUMANOID_MAJOR_DECISIONS.filter(d => d.age === age);
  }

  if (matches.length === 0) return null;

  // กรองตัวเลือกที่ยังไม่เคยเจอในชาตินี้ (Non-Repetitive Choice)
  const unseen = matches.filter(d => !seenDecisionIds.has(d.id));
  const candidatePool = unseen.length > 0 ? unseen : matches;

  // สุ่ม 1 ตัวจากตัวเลือกของอายุดังกล่าว เพื่อความหลากหลายในการเล่นแต่ละรอบ
  const chosen = candidatePool[Math.floor(Math.random() * candidatePool.length)];

  if (chosen?.id && seenDecisionIds) {
    seenDecisionIds.add(chosen.id);
  }

  return chosen;
}

