// เราสามารถ parse RACES array แล้วเติม fields หรือ regex match
let updatedContent = content;

for (const [id, data] of Object.entries(raceData)) {
  // Regex เพื่อหา block ของ race id นี้
  const racePattern = new RegExp(`(\\{\\s*id:\\s*'${id}'[\\s\\S]*?)(desc:\\s*'[^']*')(,?\\s*\\n?)`, 'm');
  const match = updatedContent.match(racePattern);
  if (match) {
    let addition = `${match[2]},\n`;
    if (data.portrait) {
      addition += `    portrait: '${data.portrait}',\n`;
    }
    addition += `    appearance: '${data.appearance}',\n`;
    addition += `    strengths: '${data.strengths}',\n`;
    addition += `    weaknesses: '${data.weaknesses}'`;
    
    // ตรวจสอบว่ามี appearance อยู่แล้วหรือไม่
    if (!match[1].includes('appearance:')) {
      updatedContent = updatedContent.replace(match[0], `${match[1]}${addition}\n  }`);
      console.log(`Updated race: ${id}`);
    } else {
      console.log(`Race already has appearance: ${id}`);
    }
  } else {
    console.warn(`Could not match race: ${id}`);
  }
}

fs.writeFileSync(filePath, updatedContent, 'utf8');
console.log('Finished updating birthData.js');
